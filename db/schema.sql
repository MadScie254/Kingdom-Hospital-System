-- Kingdom Faith Based Hospital: PostgreSQL schema for Neon.
-- Each collection is a table of JSON documents with a serial id. Constraints that matter
-- for safety (unique numbers, one active admission, no negative stock) are enforced here.
create extension if not exists pgcrypto;

do $$
declare t text;
begin
  foreach t in array array['settings','departments','doctors','nurses','staff','patients','visits','appointments','emergencies','prescriptions','medicines','inventory','lab_catalog','lab_orders','beds','admissions','services','invoices','payments','expenses','pharmacy_sales','ambulances','bookings','dental','sha_claims','holidays','schedules','symptoms','diagnoses','treatments','advice','documents','templates','imaging','plans','attendance']
  loop
    execute format('create table if not exists %I (id integer generated by default as identity primary key, data jsonb not null default ''{}''::jsonb, created_at timestamptz not null default now(), updated_at timestamptz not null default now())', t);
  end loop;
end $$;

create sequence if not exists patient_mrn_seq start 100300;
create sequence if not exists invoice_no_seq start 1271;
create sequence if not exists sha_claim_seq start 314;

create unique index if not exists patients_mrn_key on patients ((data->>'mrn'));
create unique index if not exists invoices_no_key on invoices ((data->>'no'));
create unique index if not exists sha_claims_no_key on sha_claims ((data->>'claimNo'));
create unique index if not exists beds_code_key on beds ((data->>'code'));
create unique index if not exists admissions_one_per_bed on admissions ((data->>'bedId')) where data->>'status' = 'Admitted';
create unique index if not exists admissions_one_per_patient on admissions ((data->>'patientId')) where data->>'status' = 'Admitted';
create index if not exists payments_invoice_idx on payments ((data->>'invoiceNo'));
create index if not exists invoices_patient_idx on invoices ((data->>'patientId'));
create index if not exists visits_patient_idx on visits ((data->>'patientId'));
create index if not exists lab_orders_patient_idx on lab_orders ((data->>'patientId'));

do $$ begin
  alter table medicines add constraint medicines_stock_nonneg check ((data->>'quantity')::numeric >= 0);
exception when duplicate_object then null; end $$;
do $$ begin
  alter table inventory add constraint inventory_stock_nonneg check ((data->>'quantity')::numeric >= 0);
exception when duplicate_object then null; end $$;

create or replace function invoice_total(d jsonb) returns numeric language sql immutable as $$
  select (s.sub - round(s.sub * coalesce((d->>'discountPct')::numeric, 0) / 100))
       + round((s.sub - round(s.sub * coalesce((d->>'discountPct')::numeric, 0) / 100)) * coalesce((d->>'vatPct')::numeric, 0) / 100)
  from (select coalesce(sum((i->>'qty')::numeric * (i->>'price')::numeric), 0) as sub
        from jsonb_array_elements(coalesce(d->'items', '[]'::jsonb)) i) s
$$;

create table if not exists app_users (
  id serial primary key,
  email text not null,
  name text not null,
  role text not null default 'staff' check (role in ('admin', 'staff')),
  password_hash text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  last_login_at timestamptz
);
create unique index if not exists app_users_email_key on app_users (lower(email));

create table if not exists login_attempts (
  id bigserial primary key, email text not null, ok boolean not null, at timestamptz not null default now()
);
create index if not exists login_attempts_idx on login_attempts (lower(email), at desc);

create table if not exists audit_log (
  id bigserial primary key, at timestamptz not null default now(),
  actor text not null, action text not null, collection text, record_id text
);
create index if not exists audit_log_at_idx on audit_log (at desc);

-- Staff signup requests, roles and departments
alter table app_users add column if not exists status text not null default 'active';
alter table app_users add column if not exists phone text;
alter table app_users add column if not exists position text;
alter table app_users add column if not exists licence text;
alter table app_users add column if not exists departments integer[] not null default '{}';
alter table app_users add column if not exists requested_role text;
alter table app_users add column if not exists requested_at timestamptz not null default now();
alter table app_users add column if not exists approved_by text;
alter table app_users add column if not exists approved_at timestamptz;
alter table app_users add column if not exists signup_ip text;
alter table app_users drop constraint if exists app_users_role_check;
alter table app_users add constraint app_users_role_check check (role in ('admin', 'doctor', 'nurse', 'lab', 'pharmacy', 'reception', 'accounts', 'staff'));
alter table app_users drop constraint if exists app_users_status_check;
alter table app_users add constraint app_users_status_check check (status in ('pending', 'active', 'declined'));
create index if not exists app_users_status_idx on app_users (status);
create index if not exists app_users_signup_ip_idx on app_users (signup_ip, requested_at);

-- Nightly backup history
create table if not exists backup_log (
  id serial primary key,
  at timestamptz not null default now(),
  ok boolean not null,
  trigger text not null,
  tables integer,
  rows integer,
  bytes integer,
  note text
);

